// contract 保存一个已经完成签名和完整类型图校验的 RPC 接口。
type contract struct {
	pkg         *packages.Package
	name        string
	named       *types.Named
	iface       *types.Interface
	codecs      *codecRegistry
	fullName    string
	id          uint64
	fingerprint [32]byte
	methods     []*method
}

// method 保存一个 RPC 方法的固定声明顺序和生成标识。
type method struct {
	name       string
	signature  *types.Signature
	id         uint64
	inputs     []parameter
	outputs    []parameter
	hasError   bool
	notifyOnly bool
}

// parameter 使用生成期稳定名称表示一个输入或业务输出位置。
type parameter struct {
	name string
	typ  types.Type
}

// serviceBinding 表示一个具体 Service 指针实现了唯一 RPC 契约。
type serviceBinding struct {
	pkg      *packages.Package
	typeName string
	contract *contract
}

// packageOutput 聚合一个 Go 包内的契约和 Service 适配代码。
type packageOutput struct {
	pkg       *packages.Package
	contracts []*contract
	services  []serviceBinding
}

// collectContracts 从语法标记定位具名接口，并在任何生成动作前完成全部验证。
func collectContracts(
	packagesToScan []*packages.Package,
	codecs *codecRegistry,
) ([]*contract, error) {
	var result []*contract
	for _, pkg := range packagesToScan {
		if pkg.Types == nil || len(pkg.Syntax) == 0 {
			continue
		}
		for _, file := range pkg.Syntax {
			for _, declaration := range file.Decls {
				typeDecl, ok := declaration.(*ast.GenDecl)
				if !ok || typeDecl.Tok.String() != "type" {
					continue
				}
				for _, specification := range typeDecl.Specs {
					typeSpec, ok := specification.(*ast.TypeSpec)
					if !ok || !hasRPCMarker(typeDecl.Doc, typeSpec.Doc) {
						continue
					}
					if !typeSpec.Name.IsExported() {
						return nil, fmt.Errorf(
							"%s.%s: RPC 契约必须导出",
							pkg.PkgPath,
							typeSpec.Name.Name,
						)
					}
					// 别名不会建立独立契约身份，且它的 Type 不是 *types.Named。必须在
					// 解引用类型对象前明确拒绝，避免非法输入让生成器自身发生 panic。
					if typeSpec.Assign.IsValid() {
						return nil, fmt.Errorf(
							"%s.%s: RPC 契约不能使用类型别名",
							pkg.PkgPath,
							typeSpec.Name.Name,
						)
					}
					object, ok := pkg.Types.Scope().
						Lookup(typeSpec.Name.Name).(*types.TypeName)
					if !ok || object == nil {
						return nil, fmt.Errorf(
							"%s.%s: 找不到 RPC 契约类型",
							pkg.PkgPath,
							typeSpec.Name.Name,
						)
					}
					named, ok := object.Type().(*types.Named)
					if !ok || named == nil {
						return nil, fmt.Errorf(
							"%s.%s: //origin:rpc 只能标记具名接口",
							pkg.PkgPath,
							typeSpec.Name.Name,
						)
					}
					iface, ok := named.Underlying().(*types.Interface)
					if !ok || iface == nil {
						return nil, fmt.Errorf(
							"%s.%s: //origin:rpc 只能标记具名接口",
							pkg.PkgPath,
							typeSpec.Name.Name,
						)
					}
					current, err := buildContract(
						pkg,
						typeSpec.Name.Name,
						named,
						iface,
						codecs,
					)
					if err != nil {
						return nil, err
					}
					result = append(result, current)
				}
			}
		}
	}
	sort.Slice(result, func(i, j int) bool {
		return result[i].fullName < result[j].fullName
	})
	return result, validateIDCollisions(result)
}

// hasRPCMarker 要求标记位于接口 GenDecl 或 TypeSpec 的紧邻文档注释中。
func hasRPCMarker(groups ...*ast.CommentGroup) bool {
	for _, group := range groups {
		if group == nil {
			continue
		}
		for _, line := range group.List {
			if strings.TrimSpace(strings.TrimPrefix(line.Text, "//")) == "origin:rpc" {
				return true
			}
		}
	}
	return false
}

// buildContract 校验接口外观、方法签名和完整可达类型图。
func buildContract(
	pkg *packages.Package,
	name string,
	named *types.Named,
	iface *types.Interface,
	codecs *codecRegistry,
) (*contract, error) {
	// Go 泛型接口需要在使用点实例化，不具备单一稳定 Schema；首版在扫描期直接拒绝。
	if named.TypeParams() != nil && named.TypeParams().Len() != 0 {
		return nil, fmt.Errorf(
			"%s.%s: M11 不支持泛型 RPC 契约",
			pkg.PkgPath,
			name,
		)
	}
	iface.Complete()
	if iface.NumEmbeddeds() != 0 {
		return nil, fmt.Errorf("%s.%s: M11 不支持 RPC 接口嵌入", pkg.PkgPath, name)
	}
	if iface.NumMethods() == 0 {
		return nil, fmt.Errorf("%s.%s: RPC 契约至少需要一个方法", pkg.PkgPath, name)
	}
	current := &contract{
		pkg:      pkg,
		name:     name,
		named:    named,
		iface:    iface,
		codecs:   codecs,
		fullName: pkg.PkgPath + "." + name,
	}
	current.id = stableID("contract\x00" + current.fullName)

	for index := 0; index < iface.NumMethods(); index++ {
		function := iface.Method(index)
		if !function.Exported() {
			return nil, fmt.Errorf(
				"%s.%s.%s: RPC 方法必须导出",
				pkg.PkgPath,
				name,
				function.Name(),
			)
		}
		signature, _ := function.Type().(*types.Signature)
		built, err := buildMethod(current, function.Name(), signature)
		if err != nil {
			return nil, err
		}
		current.methods = append(current.methods, built)
	}
	sort.Slice(current.methods, func(i, j int) bool {
		return current.methods[i].name < current.methods[j].name
	})
	current.fingerprint = sha256.Sum256([]byte(contractSchema(current)))
	return current, nil
}

// buildMethod 固定 Context、输入和输出位置语义。
func buildMethod(owner *contract, name string, signature *types.Signature) (*method, error) {
	path := owner.fullName + "." + name
	if signature == nil || signature.TypeParams().Len() != 0 ||
		signature.RecvTypeParams().Len() != 0 {
		return nil, fmt.Errorf("%s: M11 不支持泛型 RPC 方法", path)
	}
	if signature.Variadic() {
		return nil, fmt.Errorf("%s: RPC 方法不能使用可变参数", path)
	}
	if signature.Params().Len() == 0 ||
		!isContext(signature.Params().At(0).Type()) {
		return nil, fmt.Errorf("%s: 第一个参数必须是 context.Context", path)
	}
	current := &method{
		name:      name,
		signature: signature,
		id:        stableID("method\x00" + path),
	}
	for index := 1; index < signature.Params().Len(); index++ {
		typ := signature.Params().At(index).Type()
		if isContext(typ) {
			return nil, fmt.Errorf("%s: 只能声明一个 context.Context", path)
		}
		fieldPath := fmt.Sprintf("%s.input[%d]", path, index)
		if err := validateTypeWithCodecs(
			typ,
			true,
			fieldPath,
			nil,
			0,
			owner.codecs,
		); err != nil {
			return nil, err
		}
		current.inputs = append(current.inputs, parameter{
			name: fmt.Sprintf("arg%d", index),
			typ:  typ,
		})
	}

	results := signature.Results()
	for index := 0; index < results.Len(); index++ {
		typ := results.At(index).Type()
		if isError(typ) {
			if index != results.Len()-1 || current.hasError {
				return nil, fmt.Errorf("%s: error 最多一个且必须位于最后", path)
			}
			current.hasError = true
			continue
		}
		fieldPath := fmt.Sprintf("%s.output[%d]", path, index+1)
		if err := validateTypeWithCodecs(
			typ,
			true,
			fieldPath,
			nil,
			0,
			owner.codecs,
		); err != nil {
			return nil, err
		}
		current.outputs = append(current.outputs, parameter{
			name: fmt.Sprintf("result%d", len(current.outputs)+1),
			typ:  typ,
		})
	}
	current.notifyOnly = len(current.outputs) == 0 && !current.hasError
	return current, nil
}

func stableID(value string) uint64 {
	sum := sha256.Sum256([]byte(value))
	id := binary.BigEndian.Uint64(sum[:8])
	if id == 0 {
		// 零值由 Runtime 保留为非法标识；该分支概率极低但必须确定性处理。
		return binary.BigEndian.Uint64(sum[8:16])
	}
	return id
}

// validateIDCollisions 在任何文件渲染前拒绝截断碰撞。
func validateIDCollisions(contracts []*contract) error {
	contractIDs := make(map[uint64]string, len(contracts))
	methodIDs := make(map[uint64]string)
	for _, item := range contracts {
		if previous, exists := contractIDs[item.id]; exists {
			return fmt.Errorf(
				"ContractID 碰撞: %s 与 %s",
				previous,
				item.fullName,
			)
		}
		contractIDs[item.id] = item.fullName
		for _, candidate := range item.methods {
			fullName := item.fullName + "." + candidate.name
			if previous, exists := methodIDs[candidate.id]; exists {
				return fmt.Errorf("MethodID 碰撞: %s 与 %s", previous, fullName)
			}
			methodIDs[candidate.id] = fullName
		}
	}
	return nil
}

// contractSchema 生成完整指纹的确定性规范文本。
func contractSchema(item *contract) string {
	var builder strings.Builder
	builder.WriteString("origin-rpc-schema-v1\n")
	builder.WriteString(item.fullName)
	builder.WriteByte('\n')
	for _, candidate := range item.methods {
		builder.WriteString(candidate.name)
		builder.WriteByte('(')
		for index, input := range candidate.inputs {
			if index > 0 {
				builder.WriteByte(',')
			}
			builder.WriteString(schemaTypeWithCodecs(
				input.typ,
				true,
				nil,
				item.codecs,
			))
		}
		builder.WriteString(")->(")
		for index, output := range candidate.outputs {
			if index > 0 {
				builder.WriteByte(',')
			}
			builder.WriteString(schemaTypeWithCodecs(
				output.typ,
				true,
				nil,
				item.codecs,
			))
		}
		if candidate.hasError {
			if len(candidate.outputs) > 0 {
				builder.WriteByte(',')
			}
			builder.WriteString("error")
		}
		builder.WriteString(")\n")
	}
	return builder.String()
}

// collectServiceBindings 找出扫描包中嵌入 Origin Service 且实现唯一契约的具名结构体。
func collectServiceBindings(
	packagesToScan []*packages.Package,
	contracts []*contract,
) ([]serviceBinding, error) {
	var result []serviceBinding
	for _, pkg := range packagesToScan {
		if pkg.Types == nil {
			continue
		}
		names := pkg.Types.Scope().Names()
		sort.Strings(names)
		for _, name := range names {
			object, ok := pkg.Types.Scope().Lookup(name).(*types.TypeName)
			if !ok || object.IsAlias() {
				continue
			}
			named, ok := object.Type().(*types.Named)
			if !ok {
				continue
			}
			if _, ok := named.Underlying().(*types.Struct); !ok {
				continue
			}
			pointer := types.NewPointer(named)
			var matched []*contract
			for _, candidate := range contracts {
				if types.Implements(pointer, candidate.iface) {
					matched = append(matched, candidate)
				}
			}
			if len(matched) > 1 {
				return nil, fmt.Errorf(
					"%s.%s: 一个 Service 首版只能实现一个 RPC 契约",
					pkg.PkgPath,
					name,
				)
			}
			if len(matched) == 1 && implementsOriginService(pointer) {
				result = append(result, serviceBinding{
					pkg:      pkg,
					typeName: name,
					contract: matched[0],
				})
			}
		}
	}
	return result, nil
}

// implementsOriginService 通过稳定的未导出 baseService 方法识别真实 Origin Service。
func implementsOriginService(pointer types.Type) bool {
	methodSet := types.NewMethodSet(pointer)
	for index := 0; index < methodSet.Len(); index++ {
		method := methodSet.At(index).Obj()
		if method.Name() == "baseService" &&
			method.Pkg() != nil &&
			method.Pkg().Path() == "github.com/duanhf2012/origin/v3/service" {
			return true
		}
	}
	return false
}

func packageDirectory(pkg *packages.Package) (string, error) {
	if len(pkg.GoFiles) == 0 {
		return "", fmt.Errorf("%s: 包没有可写 Go 文件", pkg.PkgPath)
	}
	return filepath.Dir(pkg.GoFiles[0]), nil
}
